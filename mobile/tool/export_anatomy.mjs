// Regenerates mobile/lib/widgets/anatomy_shapes.dart from the website's body
// map (web/src/site/components/anatomy/shapes.ts), so the app and the site
// draw the same figure. Run from the repo root:
//   node mobile/tool/export_anatomy.mjs
import { writeFileSync } from 'node:fs';

const src = new URL('../../web/src/site/components/anatomy/shapes.ts', import.meta.url);
const { HEAD, SILHOUETTE, SHAPES, VIEWBOX } = await import(src.href);

const q = (s) => `'${s}'`;
const groups = (view) =>
  Object.entries(SHAPES[view])
    .map(([g, paths]) => `    MuscleGroup.${g}: [\n${paths.map((d) => `      ${q(d)},`).join('\n')}\n    ],`)
    .join('\n');

const out = `// Generated by mobile/tool/export_anatomy.mjs from the website's body map.
// Do not edit by hand: change web/src/site/components/anatomy/shapes.ts and rerun.
// Shapes are drawn for the figure's left half (x < 100) and mirrored.

import 'dart:ui';

enum BodyView { front, back }

enum MuscleGroup { chest, shoulders, arms, back, core, legs, glutes }

const anatomyViewBox = Rect.fromLTWH(${VIEWBOX.x}, ${VIEWBOX.y}, ${VIEWBOX.w}, ${VIEWBOX.h});
const anatomyHead = Rect.fromLTWH(${HEAD.cx - HEAD.rx}, ${HEAD.cy - HEAD.ry}, ${HEAD.rx * 2}, ${HEAD.ry * 2});
const anatomySilhouette = ${q(SILHOUETTE)};

const anatomyMuscles = <BodyView, Map<MuscleGroup, List<String>>>{
  BodyView.front: {
${groups('front')}
  },
  BodyView.back: {
${groups('back')}
  },
};
`;
writeFileSync(new URL('../lib/widgets/anatomy_shapes.dart', import.meta.url), out);
console.log('Wrote anatomy_shapes.dart');
